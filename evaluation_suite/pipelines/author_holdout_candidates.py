def main():
    reg = json.loads((ROOT / "storage/chunks.json").read_text())
    by_id = {c["chunk_id"]: c for c in reg}
    corpus_text = {c["source_file"]: c["text"].lower() for c in reg}
    all_text = "\n".join(corpus_text.values())

    problems, records, review_rows = [], [], []

    for c in CANDIDATES:
        qid = c["qid"]
        doc = PAPER_FILE[c["paper"]]
        rec = {
            "qid": qid,
            "question": c["question"],
            "gold_answer": c.get("gold_answer", ""),
            "gold_pages": [c["page"]] if c["answerable"] else [],
            "gold_chunk_ids": [c["chunk_id"]] if c["answerable"] else [],
            "type": c["type"],
            "answerable": c["answerable"],
        }
        rec["_paper_file"] = doc          # review metadata (stripped before final write)
        rec["_evidence"] = c.get("evidence", "")
        rec["_absence_terms"] = c.get("absence_terms", [])

        if c["answerable"]:
            chunk = by_id.get(c["chunk_id"])
            if chunk is None:
                problems.append(f"{qid}: chunk_id {c['chunk_id']} does not exist in the registry")
                continue
            if chunk["source_file"] != doc:
                problems.append(f"{qid}: chunk {c['chunk_id']} belongs to {chunk['source_file']}, expected {doc}")
                continue
            if chunk["page"] != c["page"]:
                problems.append(f"{qid}: chunk {c['chunk_id']} is on page {chunk['page']}, expected {c['page']}")
                continue
            ev = c["evidence"]
            if ev.lower() not in chunk["text"].lower():
                problems.append(f"{qid}: evidence substring NOT found in chunk {c['chunk_id']}")
                continue
        else:
            hits = [t for t in c["absence_terms"] if t.lower() in all_text]
            if hits:
                problems.append(f"{qid}: unanswerable question FAILED absence check, found {hits} in corpus")
                continue

        review_rows.append({
            "qid": qid, "paper": PAPER[c["paper"]], "type": c["type"],
            "answerable": c["answerable"], "page": c["page"] if c["answerable"] else "",
            "chunk_id": c["chunk_id"] if c["answerable"] else "",
            "question": c["question"], "gold_answer": c["gold_answer"],
            "evidence_excerpt": (by_id[c["chunk_id"]]["text"][:280] if c["answerable"] else
                                 "verified absent from all indexed documents via keyword search: " + "; ".join(c["absence_terms"])),
            "substitution_note": "table slot substituted with a TEXT question: this paper contains no table in the indexed text" if qid == "H007" else "",
            "review_question_clear": "", "review_answer_correct": "",
            "review_page_correct": "", "review_chunk_id_correct": "",
            "review_type_correct": "", "review_answerability_correct": "",
            "review_verdict": "", "review_notes": "",
        })
        records.append(rec)

    # redundancy: within-set and vs the 60 dev questions
    def toks(q):
        return set(re.findall(r"[a-z0-9]+", q.lower()))
    dev = json.loads((ROOT / "evaluation_suite/dataset/gold_qa_dataset.json").read_text())
    dev_qs = [qa["question"] for e in dev.values() for qa in e["qa_pairs"]]
    dev_toks = [toks(q) for q in dev_qs]
    cand = [r for r in records]
    for i, r1 in enumerate(cand):
        t1 = toks(r1["question"])
        for r2 in cand[i+1:]:
            t2 = toks(r2["question"])
            if t1 & t2 and len(t1 & t2) / len(t1 | t2) > 0.6:
                problems.append(f"REDUNDANT within holdout: {r1['qid']} ~ {r2['qid']}")
        for dt in dev_toks:
            if t1 & dt and len(t1 & dt) / len(t1 | dt) > 0.6:
                problems.append(f"REDUNDANT vs dev question: {r1['qid']}")
                break

    counts = {}
    for r in records:
        counts[r["type"]] = counts.get(r["type"], 0) + 1

    report = {
        "n_candidates": len(CANDIDATES), "n_written": len(records),
        "n_problems": len(problems), "problems": problems,
        "type_counts": counts, "papers": sorted({r["_paper_file"][:10] for r in records}),
        "validation": "PASSED" if not problems else "FAILED",
        "status": "CANDIDATE — awaiting human review; not frozen, not evaluated",
        "absence_check_scope": "all 9 indexed documents (entire evaluated corpus)",
    }

    # write candidate JSONL (with review metadata carried separately)
    (ROOT / "eval/holdout.jsonl").write_text(
        "\n".join(json.dumps({k: v for k, v in r.items() if not k.startswith("_")}) for r in records))
    (ROOT / "evaluation_suite/evaluations/holdout_validation_report.json").write_text(json.dumps(report, indent=2))

    with open(ROOT / "evaluation_suite/review/holdout_review_32.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(review_rows[0].keys()))
        w.writeheader()
        w.writerows(review_rows)

    print(json.dumps(report, indent=2))
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())
