"""Classifies every evaluated case and regenerates docs/failure_analysis.md.

Classes (overlaps allowed): retrieval miss, wrong rank (2–5), low faithfulness
(<0.6), low relevancy (<0.6), possible bad gold (evidence page absent from the
parsed chunks), generation error. Purely mechanical — no LLM, no estimates.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs" / "failure_analysis.md"
RAW = ROOT / "scratch" / "failure_raw.json"


def main():
    from src.core.vector_store import get_registry

    h = json.loads((ROOT / "evaluation_suite/evaluations/retrieval_benchmark/retrieval_benchmark_hybrid_k5.json").read_text())
    ranks = {q["qid"]: q["first_relevant_rank"] for q in h["per_query"]}
    qmeta = {q["qid"]: q for q in h["per_query"]}
    gold = json.loads((ROOT / "evaluation_suite/dataset/gold_qa_dataset.json").read_text())
    answers = json.loads((ROOT / "evaluation_suite/evaluations/llm_judge/rag_answers.json").read_text())
    judge = json.loads((ROOT / "evaluation_suite/evaluations/llm_judge/judge_results.json").read_text())
    registry = get_registry()

    gold_meta = {}
    for entry in gold.values():
        for qa in entry["qa_pairs"]:
            gold_meta[qa["question_id"]] = [qa["question"], qa["evidence"].get("page")]
    doc_pages = {}
    for c in registry:
        doc_pages.setdefault(c["source_file"], set()).add(c.get("page"))
    docs = sorted(doc_pages)

    fails = {k: [] for k in ("retrieval_miss", "wrong_rank", "low_faithfulness",
                             "low_relevancy", "possible_bad_gold", "generation_error")}
    qid2doc = {}
    for qid, rank in ranks.items():
        if rank is None:
            fails["retrieval_miss"].append(qid)
        elif rank > 1:
            fails["wrong_rank"].append(qid)
        j = judge.get(qid, {})
        if isinstance(j.get("faithfulness"), (int, float)) and j["faithfulness"] < 0.6:
            fails["low_faithfulness"].append(qid)
        if isinstance(j.get("relevancy"), (int, float)) and j["relevancy"] < 0.6:
            fails["low_relevancy"].append(qid)
        prefix = qid.rsplit("_Q", 1)[0]
        doc = next((d for d in docs if d.startswith(prefix)), None)
        qid2doc[qid] = doc
        page = (gold_meta.get(qid) or [None, None])[1]
        if doc and page is not None and page not in doc_pages.get(doc, set()):
            fails["possible_bad_gold"].append(qid)
        if isinstance(j.get("faithfulness"), str):
            fails["generation_error"].append(qid)

    def qtext(qid):
        return (gold_meta.get(qid) or ["?"])[0]

    lines = ["# Failure Analysis — all 60 evaluated cases (hybrid retrieval run)",
             "",
             "Every case classified by mechanical checks; overlaps are expected (a case",
             "can be wrong-rank AND low-relevancy). No case is dropped; none estimated.",
             "Regenerated by `make eval` (run_failure_analysis.py).",
             "",
             "## Counts", "",
             "| Class | Count | Definition |", "|---|---:|---|",
             f"| Retrieval miss | {len(fails['retrieval_miss'])} | no chunk from the evidence page in top-5 |",
             f"| Wrong rank | {len(fails['wrong_rank'])} | evidence chunk retrieved but not #1 |",
             f"| Low faithfulness | {len(fails['low_faithfulness'])} | judge score < 0.6 |",
             f"| Low relevancy | {len(fails['low_relevancy'])} | judge score < 0.6 |",
             f"| Possible bad gold | {len(fails['possible_bad_gold'])} | evidence page missing from parsed chunks |",
             f"| Generation error | {len(fails['generation_error'])} | — |", ""]

    lines += ["## Retrieval misses", ""]
    for q in fails["retrieval_miss"]:
        lines.append(f"- `{q}` ({qmeta[q]['type']}) — {qtext(q)[:110]}")
    lines += ["", "## Wrong rank (ranks 2–5)", ""]
    for q in fails["wrong_rank"]:
        lines.append(f"- `{q}` (rank {ranks[q]}, {qmeta[q]['type']}) — {qtext(q)[:100]}")
    lines += ["", "## Low faithfulness", ""]
    for q in fails["low_faithfulness"]:
        r = judge[q].get("reasons", {}).get("faithfulness", "")
        lines.append(f"- `{q}` F={judge[q]['faithfulness']} ({qmeta[q]['type']}) — judge: {r[:230]}")
    lines += ["", "## Low relevancy", ""]
    for q in fails["low_relevancy"]:
        r = judge[q].get("reasons", {}).get("relevancy", "")
        lines.append(f"- `{q}` R={judge[q]['relevancy']} ({qmeta[q]['type']}) — {qtext(q)[:90]} — judge: {r[:170]}")
    lines += ["", "## Possible bad gold", ""]
    if fails["possible_bad_gold"]:
        for q in fails["possible_bad_gold"]:
            lines.append(f"- `{q}` — evidence page not present in parsed chunks")
    else:
        lines += ["All 60 evidence pages exist in the parsed chunks of their papers — the",
                  "bad-gold heuristic found no candidates. This does NOT verify the expected",
                  "answers are correct; it only rules out unsatisfiable page references.",
                  "For the human check, use `evaluation_suite/review/gold_review_30.csv`."]
    lines += ["", "## Overlap note", "",
              "Retrieval classes are disjoint (miss + wrong-rank + rank-1 hits = 60). Judge",
              "classes overlap with retrieval classes. Low-faithfulness cases with in-top-5",
              "retrieval are generation-side failures, not retrieval-side."]

    OUT.write_text("\n".join(lines))
    RAW.parent.mkdir(exist_ok=True)
    RAW.write_text(json.dumps({"fails": fails, "ranks": ranks, "qid2doc": qid2doc}, indent=2))
    print(f"[failure-analysis] wrote {OUT} | counts: "
          + ", ".join(f"{k}={len(v)}" for k, v in fails.items()))


if __name__ == "__main__":
    main()
